class _Query:
    def __init__(self, db, rows_only=True):
        self.db = db
        self.rows_only = rows_only

    def filter(self, *args, **kwargs):
        return self

    def first(self):
        return None

    def all(self):
        # Two-entity queries (row + SQL "client called" flag) find no completed rows.
        return self.db.rows if self.rows_only else []


class _Db:
    def __init__(self, rows=()):
        self.rows = list(rows)
        self.added, self.commits = [], 0

    def query(self, *args):
        return _Query(self, rows_only=len(args) == 1)

    def add_all(self, rows):
        self.added.extend(rows)

    def add(self, item):
        self.added.append(item)

    def delete(self, item):
        self.deleted = getattr(self, "deleted", []) + [item]

    def commit(self):
        self.commits += 1

    def rollback(self):
        pass


